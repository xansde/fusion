/**
 * gen-prerequisite-names.mjs — generate the client-side static EN→pt-BR
 * document-name index used to translate feat/classFeature `system.
 * prerequisites` prose (issue #32).
 *
 * WHY a generated static map instead of a live server lookup: the renderer
 * that composes a prerequisite's pt-BR text (packages/client/src/lib/
 * compendium/prerequisiteTranslation.ts) runs synchronously inside pure
 * view-model code — documentDetails.ts's field builders and planVM.ts's
 * checkFeatPrerequisites — neither of which can await a network round-trip
 * for a pack index. A committed static module (same pattern as
 * traitNames.ts, generated by gen-client-maps.mjs) keeps the renderer a
 * plain synchronous function while still resolving "by document" per the
 * issue's own diagnosis: a prerequisite string is translated by finding the
 * DOCUMENT it names and reusing that document's own translated name, so the
 * mapping improves automatically as tools/translate-packs fills in more
 * names — no separate dictionary to keep in sync by hand.
 *
 * Source: each pack's documents.json (EN `name`) + i18n.pt-BR.json (pt-BR
 * `name`, when translated). PACKS_PRIORITY controls collision order: every
 * document with a `system.prerequisites` entry lives in feats-core (verified
 * against the live pack — see docs/research), and most prerequisite text
 * names a SIBLING feat, so feats-core wins on a same-name collision; the
 * other packs cover subclass-axis picks (class-features-core: "Dragon
 * Instinct", "Enigma", ...), ancestry/heritage feats, backgrounds and
 * actions. A name that appears MORE THAN ONCE within the SAME pack with
 * DIFFERING pt-BR translations is dropped as ambiguous rather than guessed
 * (62 known homonyms across packs motivated this — see issue #32 notes).
 *
 * Output: packages/client/src/lib/compendium/documentNamesPt.ts — a
 * committed static module (no runtime pack-index dependency).
 * Regenerate: node tools/translate-packs/gen-prerequisite-names.mjs && \
 *   npx prettier --write packages/client/src/lib/compendium/documentNamesPt.ts
 * (re-run whenever a pack's i18n.pt-BR.json gains more translated names —
 * this is why the compositional renderer's coverage grows over time without
 * code changes; same two-step convention as gen-client-maps.mjs/traitNames.ts).
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { buildDocumentNameIndex } from "./src/document-names.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const packsRoot = join(here, "..", "..", "systems", "pf2e", "packs");
const outPath = join(
  here,
  "..",
  "..",
  "packages",
  "client",
  "src",
  "lib",
  "compendium",
  "documentNamesPt.ts",
);

/**
 * Priority order for cross-pack name collisions — earlier wins. All
 * prerequisite-bearing documents live in feats-core, so a same-pack sibling
 * reference resolves first; class-features-core covers subclass-axis option
 * names (e.g. "Dragon Instinct", "Eldritch Trickster", "Enigma").
 */
const PACKS_PRIORITY = [
  "feats-core",
  "class-features-core",
  "ancestry-features-core",
  "heritages-core",
  "ancestries-core",
  "backgrounds-core",
  "actions-core",
];

function loadPack(pack) {
  const docsPath = join(packsRoot, pack, "documents.json");
  const overlayPath = join(packsRoot, pack, "i18n.pt-BR.json");
  const docs = JSON.parse(readFileSync(docsPath, "utf-8"));
  let overlay = { entries: {} };
  if (existsSync(overlayPath)) {
    overlay = JSON.parse(readFileSync(overlayPath, "utf-8"));
  }
  return { docs, overlay };
}

function buildIndex() {
  let totalDocs = 0;
  const packsInPriorityOrder = PACKS_PRIORITY.map((pack) => {
    const { docs, overlay } = loadPack(pack);
    totalDocs += docs.length;
    return { docs, overlay };
  });

  const index = buildDocumentNameIndex(packsInPriorityOrder);
  const totalTranslated = packsInPriorityOrder.reduce(
    (sum, { docs, overlay }) => sum + docs.filter((d) => overlay.entries[d._id]?.name).length,
    0,
  );

  return { index, totalDocs, totalTranslated };
}

function serialize(map) {
  const entries = [...map.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([en, pt]) => `  ${JSON.stringify(en)}: ${JSON.stringify(pt)},`)
    .join("\n");
  return entries;
}

const { index, totalDocs, totalTranslated } = buildIndex();

const header = `/**
 * documentNamesPt.ts — GENERATED. Do not edit by hand.
 *
 * EN document name (lowercased) → pt-BR translated name, merged across
 * ${PACKS_PRIORITY.join(", ")}
 * in that priority order (a same-name collision keeps the earliest pack's
 * translation; a same-pack collision with differing translations is
 * dropped as ambiguous). Used by prerequisiteTranslation.ts to translate
 * feat/classFeature \`system.prerequisites\` prose "by document" (issue #32)
 * — a prerequisite naming a feat/class-feature/heritage/... resolves to
 * that document's own pt-BR name, so this map grows automatically as
 * tools/translate-packs fills in more names.
 *
 * Regenerate: node tools/translate-packs/gen-prerequisite-names.mjs
 * (source packs currently carry ${String(totalTranslated)} translated names
 * out of ${String(totalDocs)} documents across the packs above).
 */
`;

const body = `export const DOCUMENT_NAMES_PT: Readonly<Record<string, string>> = Object.freeze({\n${serialize(index)}\n});\n`;

writeFileSync(outPath, header + "\n" + body, "utf-8");
console.log(
  `Wrote ${outPath}\n  names=${index.size} (from ${totalTranslated} translated / ${totalDocs} total docs)`,
);
