export type IconName = keyof typeof NODES;

/** Every icon name of the set, sorted. */
export const ICON_NAMES: readonly IconName[] = Object.keys(NODES).sort() as IconName[];

export function isIconName(value: string): value is IconName {
  return Object.prototype.hasOwnProperty.call(NODES, value);
}

export interface IconSvgOptions {
  /** Rendered width and height in px (default 20). */
  readonly size?: number;
  /** Stroke width in grid units (default 1.75 — the set's weight; change only with reason). */
  readonly strokeWidth?: number;
  /**
   * Accessible name. Without it the icon is decorative (`aria-hidden`): the button or label
   * next to it carries the name. With it, the icon is `role="img"`.
   */
  readonly label?: string | undefined;
  /** Extra class on the <svg>. */
  readonly className?: string | undefined;
}

function escapeAttr(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/** SVG markup of one icon. Throws for a name outside the set (a typo must not render blank). */
export function iconSvg(name: IconName, options: IconSvgOptions = {}): string {
  if (!isIconName(name)) throw new Error(`unknown icon: ${String(name)}`);
  const size = options.size ?? 20;
  const strokeWidth = options.strokeWidth ?? 1.75;
  const a11y =
    options.label !== undefined && options.label !== ""
      ? `role="img" aria-label="${escapeAttr(options.label)}"`
      : 'aria-hidden="true"';
  const cls = options.className ? ` class="${escapeAttr(options.className)}"` : "";
  const body = NODES[name]
    .map(([tag, attrs]) => {
      const list = Object.entries(attrs)
        .map(([k, v]) => `${k}="${escapeAttr(v)}"`)
        .join(" ");
      return `<${tag} ${list}/>`;
    })
    .join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${String(size)}" ` +
    `height="${String(size)}" fill="none" stroke="currentColor" stroke-width="${String(strokeWidth)}" ` +
    `stroke-linecap="round" stroke-linejoin="round" focusable="false" ${a11y}${cls}>${body}</svg>`
  );
}
